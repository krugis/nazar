"""``nazar init``: config, CrowdSec machine registration, secrets, checks (LLD 12).

Idempotent: existing config and secrets are kept; only missing pieces are created. The
filesystem root and the command runner are injectable so this is testable without root.
"""

from __future__ import annotations

import json
import os
import pwd
import secrets
import subprocess
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path

import yaml

from nazar.config import HMAC_KEY_ENV, parse_env_file
from nazar.core.clock import SystemClock
from nazar.store import Store

NAZAR_USER = "nazar"
CAPTCHA_BOUNCER_HINTS = ("nginx", "openresty", "traefik", "cloudflare", "haproxy")

Runner = Callable[[Sequence[str]], "subprocess.CompletedProcess[str]"]


def run_command(argv: Sequence[str]) -> subprocess.CompletedProcess[str]:
    """Run without a shell, capture output, 30 s timeout."""
    return subprocess.run(  # noqa: S603 - fixed argv, no shell
        list(argv), capture_output=True, text=True, timeout=30, check=False
    )


@dataclass(frozen=True)
class Paths:
    root: Path = Path("/")

    @property
    def etc(self) -> Path:
        return self.root / "etc" / "nazar"

    @property
    def config(self) -> Path:
        return self.etc / "config.yaml"

    @property
    def secrets(self) -> Path:
        return self.etc / "secrets.env"

    @property
    def state(self) -> Path:
        return self.root / "var" / "lib" / "nazar"


@dataclass
class InitReport:
    steps: list[tuple[str, str, str]] = field(default_factory=list)
    """(step, status, detail) with status ``ok``, ``skipped``, ``created``, ``warning``,
    ``error``."""
    suggestions: list[str] = field(default_factory=list)

    def add(self, step: str, status: str, detail: str = "") -> None:
        self.steps.append((step, status, detail))

    @property
    def failed(self) -> bool:
        return any(status == "error" for _, status, _ in self.steps)


_REPO_EXAMPLE = Path(__file__).resolve().parents[2] / "examples" / "config.yaml"


def example_config() -> str:
    """The packaged example config, or the source checkout's copy in development."""
    try:
        packaged = resources.files("nazar") / "data" / "config.example.yaml"
        return packaged.read_text(encoding="utf-8")
    except (FileNotFoundError, NotADirectoryError):
        return _REPO_EXAMPLE.read_text(encoding="utf-8")


def _nazar_ids() -> tuple[int, int] | None:
    try:
        entry = pwd.getpwnam(NAZAR_USER)
    except KeyError:
        return None
    return entry.pw_uid, entry.pw_gid


def _chown(path: Path, ids: tuple[int, int] | None, group_only: bool = False) -> None:
    if ids is None or os.geteuid() != 0:
        return
    uid, gid = ids
    os.chown(path, -1 if group_only else uid, gid)


def _write_secrets(path: Path, values: dict[str, str]) -> None:
    body = "# Nazar secrets. Mode 0600. Generated by `nazar init`; edit with care.\n"
    body += "".join(f"{k}={v}\n" for k, v in sorted(values.items()))
    tmp = path.with_suffix(".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(body)
    os.replace(tmp, path)
    os.chmod(path, 0o600)


def register_machine(machine_id: str, run: Runner, force: bool = False) -> str:
    """Create the CrowdSec machine and return its password.

    The credentials go to stdout (``-f -``), never to the default credentials file, which
    belongs to the CrowdSec agent.
    """
    argv = ["cscli", "machines", "add", machine_id, "--auto", "-f", "-"]
    if force:
        argv.append("--force")
    try:
        proc = run(argv)
    except (OSError, subprocess.SubprocessError) as exc:
        raise RuntimeError(f"cannot run cscli: {type(exc).__name__}") from exc
    if proc.returncode != 0:
        msg = (proc.stderr or proc.stdout or "").strip().splitlines()
        raise RuntimeError(f"cscli machines add failed: {msg[-1] if msg else proc.returncode}")
    try:
        creds = yaml.safe_load(proc.stdout)
    except yaml.YAMLError as exc:
        raise RuntimeError("cscli printed unexpected output") from exc
    password = creds.get("password") if isinstance(creds, dict) else None
    if not password:
        raise RuntimeError("cscli output has no password")
    return str(password)


def detect_captcha_bouncers(run: Runner) -> list[str]:
    try:
        proc = run(["cscli", "bouncers", "list", "-o", "json"])
        bouncers = json.loads(proc.stdout or "[]") if proc.returncode == 0 else []
    except (OSError, subprocess.SubprocessError, ValueError):
        return []
    found = []
    for b in bouncers if isinstance(bouncers, list) else []:
        if not isinstance(b, dict):
            continue
        label = f"{b.get('name', '')} {b.get('type', '')}".lower()
        if any(hint in label for hint in CAPTCHA_BOUNCER_HINTS):
            found.append(str(b.get("name")))
    return found


def init(
    paths: Paths,
    *,
    machine_id: str = "nazar",
    run: Runner = run_command,
    register: bool = True,
    force_register: bool = False,
) -> InitReport:
    """Create what is missing. Never overwrites config; merges secrets."""
    report = InitReport()
    ids = _nazar_ids()
    if ids is None:
        report.add(
            "user", "warning", f"system user {NAZAR_USER!r} not found (install.sh creates it)"
        )

    paths.etc.mkdir(mode=0o750, parents=True, exist_ok=True)
    _chown(paths.etc, ids, group_only=True)
    if paths.config.exists():
        # Content is never touched, but the service user must be able to read it.
        mode = paths.config.stat().st_mode & 0o777
        os.chmod(paths.config, (mode | 0o040) & ~0o007)
        _chown(paths.config, ids, group_only=True)
        report.add("config", "skipped", f"{paths.config} exists, content left unchanged")
    else:
        text = example_config()
        if machine_id != "nazar":
            text = text.replace("machine_id: nazar", f"machine_id: {machine_id}")
        paths.config.write_text(text, encoding="utf-8")
        os.chmod(paths.config, 0o640)
        _chown(paths.config, ids, group_only=True)
        report.add("config", "created", str(paths.config))

    paths.state.mkdir(mode=0o750, parents=True, exist_ok=True)
    _chown(paths.state, ids)
    report.add("state dir", "ok", str(paths.state))

    current = parse_env_file(paths.secrets.read_text()) if paths.secrets.exists() else {}
    values = dict(current)
    if "NAZAR_LAPI_PASSWORD" in values and not force_register:
        report.add("crowdsec machine", "skipped", "password already in secrets.env")
    elif not register:
        report.add("crowdsec machine", "skipped", "--skip-register")
    else:
        try:
            values["NAZAR_LAPI_PASSWORD"] = register_machine(machine_id, run, force_register)
            report.add("crowdsec machine", "created", f"machine {machine_id!r} registered")
        except RuntimeError as exc:
            hint = (
                " (use --force-register to reset an existing machine)"
                if "exist" in str(exc)
                else ""
            )
            report.add("crowdsec machine", "error", f"{exc}{hint}")
    if HMAC_KEY_ENV not in values:
        values[HMAC_KEY_ENV] = secrets.token_hex(32)
        report.add("hmac key", "created", "callback signing key generated")
    if values != current or not paths.secrets.exists():
        _write_secrets(paths.secrets, values)
        _chown(paths.secrets, ids)
        report.add("secrets", "ok", f"{paths.secrets} (0600)")

    captcha = detect_captcha_bouncers(run)
    if captcha:
        report.suggestions.append(
            "captcha-capable bouncer found (" + ", ".join(captcha) + "): set "
            "policy.captcha_available: true to allow captcha decisions"
        )
    return report


def prepare_database(path: Path) -> None:
    """Create and migrate the database, owned by the service user."""
    Store(path, SystemClock()).close()
    ids = _nazar_ids()
    for file in (path, path.with_name(path.name + "-wal"), path.with_name(path.name + "-shm")):
        if file.exists():
            _chown(file, ids)


def apply_secrets_to_env(paths: Paths) -> None:
    """Make freshly written secrets visible to the checks that follow in the same process."""
    if paths.secrets.exists():
        for key, value in parse_env_file(paths.secrets.read_text()).items():
            os.environ[key] = value
